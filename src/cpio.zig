const std = @import("std");

const ASCII_CPIO_HEADER_SIZE = 110;
const TRAILER = "TRAILER!!!";

const CpioHeader = struct {
    magic: u32 = 0x070701,
    ino: u32,
    mode: u32,
    uid: u32 = 0,
    gid: u32 = 0,
    nlink: u32,
    mtime: u32,
    filesize: u32 = 0,
    devmajor: u32 = 0,
    devminor: u32 = 0,
    rdevmajor: u32 = 0,
    rdevminor: u32 = 0,
    namesize: u32,
    check: u32 = 0,
};

const CpioEntryType = enum {
    Directory,
    File,
    Symlink,
    CharacterDevice,
    BlockDevice,
    Fifo,
    Socket,

    fn toMode(self: @This(), perms: u32) u32 {
        return @as(u32, switch (self) {
            .Directory => std.os.linux.S.IFDIR | perms,
            .File => std.os.linux.S.IFREG | perms,
            .Symlink => std.os.linux.S.IFLNK | 0o777, // symlinks are always 0o777
            .CharacterDevice => std.os.linux.S.IFCHR | perms,
            .BlockDevice => std.os.linux.S.IFBLK | perms,
            .Fifo => std.os.linux.S.IFIFO | perms,
            .Socket => std.os.linux.S.IFSOCK | perms,
        });
    }

    /// Whether entries of this type carry data.
    fn hasData(self: @This()) bool {
        return switch (self) {
            .File, .Symlink => true,
            .Directory, .CharacterDevice, .BlockDevice, .Fifo, .Socket => false,
        };
    }
};

/// The device number of a character or block device.
const Device = struct {
    major: u32 = 0,
    minor: u32 = 0,
};

pub const CpioArchive = @This();

writer: *std.Io.Writer,
ino: u32 = 0,
total_written: usize = 0,

const Error = error{
    FileTooLarge,
    UnexpectedSource,
    FilesystemLoop,
};

pub fn init(writer: *std.Io.Writer) !@This() {
    return @This(){ .writer = writer };
}

pub fn addEntry(
    self: *@This(),
    source: ?*std.Io.Reader,
    filesize: u32,
    path: []const u8,
    entry_type: CpioEntryType,
    perms: u32,
) !void {
    try self.writeEntry(source, filesize, path, entry_type, perms, .{});
}

fn writeEntry(
    self: *@This(),
    source: ?*std.Io.Reader,
    filesize: u32,
    path: []const u8,
    entry_type: CpioEntryType,
    perms: u32,
    rdev: Device,
) !void {
    if (!entry_type.hasData() and source != null) {
        return Error.UnexpectedSource;
    }

    const filepath_len = path.len + 1; // null terminator

    // write entry to archive
    {
        const header = CpioHeader{
            .ino = self.ino,
            .mode = entry_type.toMode(perms),
            .uid = 0,
            .gid = 0,
            .nlink = if (entry_type == .Directory) 2 else 1,
            .filesize = filesize,
            .devmajor = 0,
            .devminor = 0,
            .rdevmajor = rdev.major,
            .rdevminor = rdev.minor,
            .mtime = 0,
            .namesize = @intCast(filepath_len),
        };

        try self.writer.print("{X:0>6}{X:0>8}{X:0>8}{X:0>8}{X:0>8}{X:0>8}{X:0>8}{X:0>8}{X:0>8}{X:0>8}{X:0>8}{X:0>8}{X:0>8}{X:0>8}", .{
            header.magic,
            header.ino,
            header.mode,
            header.uid,
            header.gid,
            header.nlink,
            header.mtime,
            header.filesize,
            header.devmajor,
            header.devminor,
            header.rdevmajor,
            header.rdevminor,
            header.namesize,
            header.check,
        });
        self.total_written += ASCII_CPIO_HEADER_SIZE;

        try self.writer.writeAll(path);
        try self.writer.writeByte(0); // null terminator
        self.total_written += filepath_len;

        // pad the file name
        const header_padding = (4 - ((ASCII_CPIO_HEADER_SIZE + filepath_len) % 4)) % 4;
        try self.writer.splatByteAll(0, header_padding);
        self.total_written += header_padding;

        if (source) |source_| {
            var streamed_bytes: usize = 0;
            while (source_.stream(self.writer, .unlimited)) |n| {
                streamed_bytes += n;
            } else |err| switch (err) {
                error.EndOfStream => {},
                else => return err,
            }

            self.total_written += streamed_bytes;

            // pad the file data
            const filedata_padding: usize = @intCast((4 - (streamed_bytes % 4)) % 4);
            try self.writer.splatByteAll(0, filedata_padding);
            self.total_written += filedata_padding;
        }
    }

    self.ino += 1;
}

pub fn addFile(
    self: *@This(),
    io: std.Io,
    path: []const u8,
    file: std.Io.File,
    size: u32,
    permissions: std.Io.File.Permissions,
) !void {
    var buffer: [1024]u8 = undefined;
    var reader = file.reader(io, &buffer);

    try self.addEntry(&reader.interface, size, path, .File, @backingInt(permissions));
}

pub fn addDirectory(self: *@This(), path: []const u8, perms: u32) !void {
    try self.addEntry(null, 0, path, .Directory, perms);
}

pub fn addSymlink(
    self: *@This(),
    dst_path: []const u8,
    src_path: []const u8,
) !void {
    var reader: std.Io.Reader = .fixed(src_path);

    try self.addEntry(
        &reader,
        @intCast(src_path.len),
        dst_path,
        .Symlink,
        0o777, // make symlinks always have 777 perms
    );
}

pub fn addCharacterDevice(self: *@This(), path: []const u8, perms: u32, major: u32, minor: u32) !void {
    try self.writeEntry(null, 0, path, .CharacterDevice, perms, .{ .major = major, .minor = minor });
}

pub fn addBlockDevice(self: *@This(), path: []const u8, perms: u32, major: u32, minor: u32) !void {
    try self.writeEntry(null, 0, path, .BlockDevice, perms, .{ .major = major, .minor = minor });
}

pub fn addFifo(self: *@This(), path: []const u8, perms: u32) !void {
    try self.addEntry(null, 0, path, .Fifo, perms);
}

pub fn addSocket(self: *@This(), path: []const u8, perms: u32) !void {
    try self.addEntry(null, 0, path, .Socket, perms);
}

pub fn finalize(self: *@This()) !void {
    try self.addEntry(null, 0, TRAILER, .File, 0);

    // Maintain a block size of 512 by adding padding to the end of the
    // archive.
    try self.writer.splatByteAll(0, (512 - (self.total_written % 512)) % 512);
    try self.writer.flush();
}

fn handleFile(
    io: std.Io,
    arena: *std.heap.ArenaAllocator,
    kind: std.Io.File.Kind,
    filename: []const u8,
    current_directory: []const u8,
    starting_directory: []const u8,
    archive: *CpioArchive,
    directory: *std.Io.Dir,
    ancestors: *std.ArrayList(DirId),
) anyerror!void {
    // The path this entry will have inside the archive.
    const entry_path = try std.fs.path.join(
        arena.allocator(),
        &.{ current_directory, filename },
    );

    switch (kind) {
        .directory => {
            var sub_directory = try directory.openDir(
                io,
                filename,
                .{ .iterate = true },
            );
            defer sub_directory.close(io);

            try archive.addDirectory(entry_path, 0o755);

            try walkEntries(
                io,
                arena,
                starting_directory,
                archive,
                &sub_directory,
                entry_path,
                ancestors,
            );
        },
        .file => {
            var file = try directory.openFile(io, filename, .{});
            defer file.close(io);

            const stat = try file.stat(io);

            if (stat.size > std.math.maxInt(u32)) {
                return Error.FileTooLarge;
            }

            try archive.addFile(
                io,
                entry_path,
                file,
                @intCast(stat.size),
                stat.permissions,
            );
        },
        .sym_link => {
            // Fully resolve the link, following any chain of links.
            var target_buf: [std.fs.max_path_bytes]u8 = undefined;
            const target_len = directory.realPathFile(io, filename, &target_buf) catch |err| switch (err) {
                // The link is dangling (or loops), so there is nothing to
                // copy. Archive it unchanged; its target may exist wherever
                // the archive is extracted.
                error.FileNotFound, error.NotDir, error.SymLinkLoop => {
                    const link_len = try directory.readLink(io, filename, &target_buf);
                    try archive.addSymlink(entry_path, target_buf[0..link_len]);
                    return;
                },
                else => return err,
            };
            const target_path = try std.fs.path.relative(
                arena.allocator(),
                ".",
                null,
                starting_directory,
                target_buf[0..target_len],
            );

            const outside_tree = std.fs.path.isAbsolute(target_path) or
                std.mem.eql(u8, target_path, "..") or
                std.mem.startsWith(u8, target_path, ".." ++ std.fs.path.sep_str);

            if (outside_tree) {
                // The target will not be in the archive, so archive a copy of
                // it in place of the link. Opening the link follows it.
                const stat = try directory.statFile(io, filename, .{});

                try handleFile(
                    io,
                    arena,
                    stat.kind,
                    filename,
                    current_directory,
                    starting_directory,
                    archive,
                    directory,
                    ancestors,
                );
            } else {
                // Symlink targets are resolved relative to the directory
                // containing the link. Both paths are archive paths; anchor
                // them at "/" since `relative` does not accept an empty path.
                const link_target = try std.fs.path.relative(
                    arena.allocator(),
                    "/",
                    null,
                    try std.fs.path.join(arena.allocator(), &.{ "/", current_directory }),
                    try std.fs.path.join(arena.allocator(), &.{ "/", target_path }),
                );

                try archive.addSymlink(entry_path, link_target);
            }
        },
        .character_device, .block_device, .named_pipe, .unix_domain_socket => {
            // Follows symlinks, for links out of the tree that are being
            // archived as a copy of their target.
            const stx = try statx(
                directory.*,
                try arena.allocator().dupeSentinel(u8, filename, 0),
                0,
                .{ .MODE = true },
            );
            const perms: u32 = stx.mode & 0o7777;

            switch (kind) {
                .character_device => try archive.addCharacterDevice(entry_path, perms, stx.rdev_major, stx.rdev_minor),
                .block_device => try archive.addBlockDevice(entry_path, perms, stx.rdev_major, stx.rdev_minor),
                .named_pipe => try archive.addFifo(entry_path, perms),
                .unix_domain_socket => try archive.addSocket(entry_path, perms),
                else => unreachable,
            }
        },
        else => std.log.warn(
            "Do not know how to add file {s} of kind {} to CPIO archive",
            .{ entry_path, kind },
        ),
    }
}

/// Identifies a directory regardless of the path used to reach it.
const DirId = struct {
    dev_major: u32,
    dev_minor: u32,
    ino: u64,

    fn of(directory: std.Io.Dir) !DirId {
        const stx = try statx(directory, "", std.os.linux.AT.EMPTY_PATH, .{ .INO = true });
        return .{ .dev_major = stx.dev_major, .dev_minor = stx.dev_minor, .ino = stx.ino };
    }
};

/// `std.Io.File.Stat` lacks device numbers, so get them from the kernel.
fn statx(
    directory: std.Io.Dir,
    sub_path: [*:0]const u8,
    flags: u32,
    mask: std.os.linux.STATX,
) !std.os.linux.Statx {
    const linux = std.os.linux;
    var stx: linux.Statx = undefined;
    const rc = linux.statx(directory.handle, sub_path, flags, mask, &stx);
    return switch (linux.errno(rc)) {
        .SUCCESS => stx,
        .NOENT => error.FileNotFound,
        .ACCES => error.AccessDenied,
        else => |err| std.posix.unexpectedErrno(err),
    };
}

/// Adds the contents of `directory`, whose path inside the archive is
/// `archive_path`. `ancestors` holds the directories currently being walked.
fn walkEntries(
    io: std.Io,
    arena: *std.heap.ArenaAllocator,
    starting_directory: []const u8,
    archive: *CpioArchive,
    directory: *std.Io.Dir,
    archive_path: []const u8,
    ancestors: *std.ArrayList(DirId),
) anyerror!void {
    // Following symlinks out of the tree can lead back into a directory we
    // are already inside of. The kernel cannot detect this (each lookup
    // follows a single link), so check for it here.
    const id = try DirId.of(directory.*);
    for (ancestors.items) |ancestor| {
        if (std.meta.eql(ancestor, id)) {
            std.log.warn("Filesystem loop: {s} leads back to a directory that contains it", .{archive_path});
            return Error.FilesystemLoop;
        }
    }
    try ancestors.append(arena.allocator(), id);
    defer _ = ancestors.pop();

    var iter = directory.iterate();

    while (try iter.next(io)) |dir_entry| {
        try handleFile(
            io,
            arena,
            dir_entry.kind,
            dir_entry.name,
            archive_path,
            starting_directory,
            archive,
            directory,
            ancestors,
        );
    }
}

pub fn walkDirectory(
    io: std.Io,
    arena: *std.heap.ArenaAllocator,
    starting_directory: []const u8,
    archive: *CpioArchive,
    directory: *std.Io.Dir,
) anyerror!void {
    var fullpath_buf: [std.fs.max_path_bytes]u8 = undefined;
    const fullpath_len = try directory.realPathFile(io, ".", &fullpath_buf);
    const directory_path = try std.fs.path.relative(
        arena.allocator(),
        ".",
        null,
        starting_directory,
        fullpath_buf[0..fullpath_len],
    );

    // We don't need to add the root directory, as it will already exist.
    if (!std.mem.eql(u8, directory_path, "")) {
        // Before iterating through the directory, add the directory itself to
        // the archive.
        try archive.addDirectory(directory_path, 0o755);
    }

    var ancestors: std.ArrayList(DirId) = .empty;

    try walkEntries(
        io,
        arena,
        starting_directory,
        archive,
        directory,
        directory_path,
        &ancestors,
    );
}

const testing = std.testing;

const TestEntry = struct {
    name: []const u8,
    mode: u32,
    ino: u32,
    nlink: u32,
    rdev_major: u32,
    rdev_minor: u32,
    data: []const u8,
};

/// Parses a newc archive produced by `CpioArchive` and checks its framing.
/// Stops at (and does not return) the trailer entry.
fn parseArchive(gpa: std.mem.Allocator, bytes: []const u8) ![]TestEntry {
    var entries: std.ArrayList(TestEntry) = .empty;
    errdefer entries.deinit(gpa);

    var pos: usize = 0;
    while (true) {
        try testing.expectEqual(@as(usize, 0), pos % 4);
        const header = bytes[pos..][0..ASCII_CPIO_HEADER_SIZE];
        try testing.expectEqualStrings("070701", header[0..6]);

        var fields: [13]u32 = undefined;
        for (&fields, 0..) |*field, i| {
            field.* = try std.fmt.parseInt(u32, header[6 + i * 8 ..][0..8], 16);
        }
        const filesize = fields[6];
        const namesize = fields[11];

        const name_start = pos + ASCII_CPIO_HEADER_SIZE;
        try testing.expectEqual(@as(u8, 0), bytes[name_start + namesize - 1]);
        const name = bytes[name_start..][0 .. namesize - 1];

        const data_start = std.mem.alignForward(usize, name_start + namesize, 4);
        for (bytes[name_start + namesize .. data_start]) |b| try testing.expectEqual(@as(u8, 0), b);
        const data = bytes[data_start..][0..filesize];

        pos = std.mem.alignForward(usize, data_start + filesize, 4);
        for (bytes[data_start + filesize .. pos]) |b| try testing.expectEqual(@as(u8, 0), b);

        if (std.mem.eql(u8, name, TRAILER)) break;

        try entries.append(gpa, .{
            .name = name,
            .ino = fields[0],
            .mode = fields[1],
            .nlink = fields[4],
            .rdev_major = fields[9],
            .rdev_minor = fields[10],
            .data = data,
        });
    }

    // Everything after the trailer is block padding.
    try testing.expectEqual(@as(usize, 0), bytes.len % 512);
    for (bytes[pos..]) |b| try testing.expectEqual(@as(u8, 0), b);

    return entries.toOwnedSlice(gpa);
}

fn findEntry(entries: []const TestEntry, name: []const u8) ?TestEntry {
    for (entries) |entry| {
        if (std.mem.eql(u8, entry.name, name)) return entry;
    }
    return null;
}

