test "walkDirectory" {
    const io = testing.io;
    var tmp = testing.tmpDir(.{ .iterate = true });
    defer tmp.cleanup();

    try tmp.dir.createDirPath(io, "etc/conf.d");
    try tmp.dir.writeFile(io, .{ .sub_path = "init", .data = "init" });
    try tmp.dir.writeFile(io, .{ .sub_path = "etc/hostname", .data = "box\n" });
    try tmp.dir.writeFile(io, .{ .sub_path = "etc/conf.d/net", .data = "" });
    try tmp.dir.symLink(io, "etc/hostname", "hostname", .{});

    var arena = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena.deinit();

    var root_buf: [std.fs.max_path_bytes]u8 = undefined;
    const root_len = try tmp.dir.realPathFile(io, ".", &root_buf);

    var buf: [8192]u8 = undefined;
    var writer: std.Io.Writer = .fixed(&buf);
    var archive = try CpioArchive.init(&writer);
    try CpioArchive.walkDirectory(io, &arena, root_buf[0..root_len], &archive, &tmp.dir);
    try archive.finalize();

    const entries = try parseArchive(testing.allocator, writer.buffered());
    defer testing.allocator.free(entries);

    try testing.expectEqual(@as(usize, 6), entries.len);

    const init_file = findEntry(entries, "init") orelse return error.TestUnexpectedResult;
    try testing.expectEqualStrings("init", init_file.data);
    try testing.expectEqual(std.os.linux.S.IFREG, init_file.mode & std.os.linux.S.IFMT);

    const hostname = findEntry(entries, "etc/hostname") orelse return error.TestUnexpectedResult;
    try testing.expectEqualStrings("box\n", hostname.data);

    const net = findEntry(entries, "etc/conf.d/net") orelse return error.TestUnexpectedResult;
    try testing.expectEqualStrings("", net.data);

    for ([_][]const u8{ "etc", "etc/conf.d" }) |name| {
        const dir = findEntry(entries, name) orelse return error.TestUnexpectedResult;
        try testing.expectEqual(@as(u32, std.os.linux.S.IFDIR | 0o755), dir.mode);
    }

    const link = findEntry(entries, "hostname") orelse return error.TestUnexpectedResult;
    try testing.expectEqual(@as(u32, std.os.linux.S.IFLNK | 0o777), link.mode);
    try testing.expectEqualStrings("etc/hostname", link.data);

    // Parent directories must come before their contents.
    for (entries, 0..) |entry, i| {
        const parent = std.fs.path.dirname(entry.name) orelse continue;
        for (entries[0..i]) |earlier| {
            if (std.mem.eql(u8, earlier.name, parent)) break;
        } else return error.TestUnexpectedResult;
    }
}

