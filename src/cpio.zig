test "walkDirectory devices, FIFOs and sockets" {
    const io = testing.io;
    const linux = std.os.linux;
    var tmp = testing.tmpDir(.{ .iterate = true });
    defer tmp.cleanup();

    // Creating device nodes needs privileges, but FIFOs and socket files do
    // not. For a device, link to /dev/null: it is outside the tree, so it is
    // archived as a copy of the device.
    for ([_]struct { [*:0]const u8, u32 }{
        .{ "fifo", linux.S.IFIFO | 0o640 },
        .{ "sock", linux.S.IFSOCK | 0o640 },
    }) |node| {
        try testing.expectEqual(.SUCCESS, linux.errno(linux.mknodat(tmp.dir.handle, node[0], node[1], 0)));
    }
    try tmp.dir.symLink(io, "/dev/null", "null", .{});

    var arena = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena.deinit();

    var root_buf: [std.fs.max_path_bytes]u8 = undefined;
    const root_len = try tmp.dir.realPathFile(io, ".", &root_buf);

    var buf: [4096]u8 = undefined;
    var writer: std.Io.Writer = .fixed(&buf);
    var archive = try CpioArchive.init(&writer);
    try CpioArchive.walkDirectory(io, &arena, root_buf[0..root_len], &archive, &tmp.dir);
    try archive.finalize();

    const entries = try parseArchive(testing.allocator, writer.buffered());
    defer testing.allocator.free(entries);

    for ([_]struct { []const u8, u32 }{
        .{ "fifo", linux.S.IFIFO },
        .{ "sock", linux.S.IFSOCK },
        .{ "null", linux.S.IFCHR },
    }) |expected| {
        const entry = findEntry(entries, expected[0]) orelse return error.TestUnexpectedResult;
        try testing.expectEqual(expected[1], entry.mode & linux.S.IFMT);
        try testing.expectEqualStrings("", entry.data);
    }

    // /dev/null is always character device 1:3 on Linux.
    const null_dev = findEntry(entries, "null") orelse return error.TestUnexpectedResult;
    try testing.expectEqual(@as(u32, 1), null_dev.rdev_major);
    try testing.expectEqual(@as(u32, 3), null_dev.rdev_minor);
}
