    defer testing.allocator.free(entries);

    for (entries) |entry| {
        try testing.expect(!std.mem.startsWith(u8, entry.name, ".."));
        try testing.expect(!std.fs.path.isAbsolute(entry.name));
    }

    // Links into the tree stay links, with targets relative to the link's
    // own directory.
    const in_subdir = findEntry(entries, "a/in_subdir") orelse return error.TestUnexpectedResult;
    try testing.expectEqual(@as(u32, std.os.linux.S.IFLNK | 0o777), in_subdir.mode);
    try testing.expectEqualStrings("b/f.txt", in_subdir.data);

    const abs_in = findEntry(entries, "abs_in") orelse return error.TestUnexpectedResult;
    try testing.expectEqual(@as(u32, std.os.linux.S.IFLNK | 0o777), abs_in.mode);
    try testing.expectEqualStrings("a/b/f.txt", abs_in.data);

    // Links out of the tree are replaced by a copy of their target.
    const out_file = findEntry(entries, "out_file") orelse return error.TestUnexpectedResult;
    try testing.expectEqual(std.os.linux.S.IFREG, out_file.mode & std.os.linux.S.IFMT);
    try testing.expectEqualStrings("outside", out_file.data);

    const sibling = findEntry(entries, "sibling") orelse return error.TestUnexpectedResult;
    try testing.expectEqual(std.os.linux.S.IFREG, sibling.mode & std.os.linux.S.IFMT);
    try testing.expectEqualStrings("sibling", sibling.data);

    for ([_][]const u8{ "a/out_dir", "a/out_dir/sub" }) |name| {
        const dir = findEntry(entries, name) orelse return error.TestUnexpectedResult;
        try testing.expectEqual(@as(u32, std.os.linux.S.IFDIR | 0o755), dir.mode);
    }
    const x = findEntry(entries, "a/out_dir/x.txt") orelse return error.TestUnexpectedResult;
    try testing.expectEqualStrings("outside", x.data);
    const d = findEntry(entries, "a/out_dir/sub/d.txt") orelse return error.TestUnexpectedResult;
    try testing.expectEqualStrings("deep", d.data);
}

